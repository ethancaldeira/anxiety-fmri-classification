"""
run_experiments.py — single orchestrator for the Ch5 and Ch6 experiments.

Subcommands:

  validate --dataset {gsp,abide}
      Negative control at the headline atlas (cc200_roi_atlas):
        validate_<dataset>_permute  — subject-level label shuffle
                                       (LABEL_PERMUTE=1); AUC should sit
                                       at chance.

  classify --dataset {gsp,abide} --atlas <name> [--connectivity {voxel,roi_roi}]
      One classification cell.

  run_standard_atlases --dataset {gsp,abide} [--connectivity {voxel,roi_roi}]
      Run all 9 standard atlases for one dataset (one classification cell each).

  compare --atlas <name> [--connectivity {voxel,roi_roi}]
      Run the same cell on BOTH datasets — direct GSP-vs-ABIDE comparison.

  run_sp_atlases --dataset {gsp,abide} [--connectivity {voxel,roi_roi}]
      Ch6 stochastic parcellation set: 4 scales (50/100/150/200 ROIs) ×
      SP_SAMPLES_PER_K samples (default 30) = 120 SP_v2_* cells per
      dataset, then the per-scale summary and the per-scale soft-vote
      ensemble of the samples.

  run_custom_atlases [--connectivity {voxel,roi_roi}]
      Ch6 individual GSP parcellations (Craddock tcorr, K = 200). GSP only;
      features are computed by anxiety-fmri-parcellations and read from
      GSP_PREPROC/{fingerprints,connectivity}/individual_ROI_200/.

  run_group_ensemble [--connectivity {voxel,roi_roi}] [--upload]
      Ch6 group parcellation ensemble. Computes features under the 3
      group-mean parcellations of the train-only STAI-T tertiles
      (group_gm_low/mid/high), trains one model per parcellation and
      averages the per-subject test probabilities (soft vote).

  all
      validate (both datasets) → run_standard_atlases (both datasets).

Standard atlases (both datasets): aal_roi_atlas, cc200_roi_atlas,
cc400_roi_atlas, dos160_roi_atlas, ez_roi_atlas, ho_roi_atlas, tt_roi_atlas,
schaefer_200_7n_yeo, schaefer_400_7n_yeo.

Results land in results/ch5/ for the Ch5 subcommands (validate, classify,
run_standard_atlases, compare, all) and results/ch6/ for the Ch6 ones
(run_sp_atlases, run_custom_atlases, run_group_ensemble). Set CHAPTER to
override.

Every cell is a fresh `python src/train.py` subprocess so TF state
doesn't bleed between runs. train.py auto-invokes the full evaluation
plot set at the end of each fit.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT    = Path(__file__).resolve().parent
TRAIN_SCRIPT = REPO_ROOT / 'src' / 'train.py'
RESULTS_ROOT = REPO_ROOT / 'results'

sys.path.insert(0, str(REPO_ROOT / 'src'))
from config import STANDARD_ATLASES  # noqa: E402

HEADLINE_ATLAS = 'cc200_roi_atlas'

# Standard atlas set used in Ch5 (src/config.py): AAL, CC200, CC400,
# Dosenbach-160, Eickhoff-Zilles, Harvard-Oxford, Talairach-Tournoux and
# Schaefer 200/400 (7 networks). All nine share the MNI152 3 mm grid and
# the same feature-compute path.
GSP_ATLASES   = STANDARD_ATLASES
ABIDE_ATLASES = STANDARD_ATLASES

# Stochastic parcellation set — Poisson-disk masks generated by
# src/generate_sp_masks.py, 30 samples × 4 scales in src/templates/atlases/.
SP_SCALES         = [50, 100, 150, 200]
# Number of samples per scale (1-30); override with SP_SAMPLES_PER_K.
SP_SAMPLES_PER_K  = int(os.environ.get('SP_SAMPLES_PER_K', '30'))
SP_ATLASES = [
    f"SP_v2_{k:03d}_{n:02d}"
    for k in SP_SCALES for n in range(1, SP_SAMPLES_PER_K + 1)
]   # SP_SAMPLES_PER_K × 4 scales atlases total

# Individual GSP parcellations (Craddock tcorr, K = 200, one per subject),
# built by anxiety-fmri-parcellations, which also computes their features
# into <FMRI_S3_BUCKET>/GSP_PREPROC/{fingerprints,connectivity}/individual_ROI_200/.
# Voxel features have the standard (31,37,31,200) supervoxel shape, so the
# 3D CNN and MLP are used unchanged.
#
# The short name is an alias — the GSP adapter (datasets/gsp.py:ATLAS_ALIASES)
# rewrites it to the feature directory name, so results dirs / plots /
# commands stay readable.
#   individual  -> individual_ROI_200   (per-subject)
CUSTOM_GSP_PARCELLATIONS = [
    'individual',
]

# Atlases trained with batch size 32 instead of 64 to limit GPU memory on a
# 16 GB T4 (400 ROIs: CC400 and Schaefer-400).
BIG_ATLAS_BATCH_OVERRIDES = {
    'cc400_roi_atlas':     '32',
    'schaefer_400_7n_yeo': '32',   # 400 ROIs, same memory profile as cc400
}


# ---------------------------------------------------------------------------
# subprocess helper
# ---------------------------------------------------------------------------

def run_one(name: str, env_overrides: dict[str, str]) -> tuple[str, int, float]:
    """Launch one train.py cell as a subprocess. Returns (name, rc, seconds)."""
    env = {**os.environ, **env_overrides, 'EXPERIMENT_NAME': name}
    print('=' * 70, flush=True)
    print(f'[run] starting {name}')
    print(f'      env: {env_overrides}')
    print('=' * 70, flush=True)
    t0 = time.time()
    proc = subprocess.run(
        [sys.executable, str(TRAIN_SCRIPT)],
        env=env,
        cwd=str(REPO_ROOT),
    )
    dt = time.time() - t0
    print(f'[run] {name} finished rc={proc.returncode} in {dt/60:.1f} min', flush=True)
    return name, proc.returncode, dt


# ---------------------------------------------------------------------------
# subcommands
# ---------------------------------------------------------------------------

def cmd_validate(dataset: str, connectivity: str = 'voxel') -> list[tuple[str, int, float]]:
    """Negative control (label-permute) at the headline atlas. AUC should
    sit at chance — if it doesn't, the model is exploiting an artefact."""
    print(f"\n{'#' * 70}\n# VALIDATE — {dataset} negative control at "
          f"{HEADLINE_ATLAS} ({connectivity})\n{'#' * 70}\n", flush=True)
    common = {
        'DATASET':           dataset,
        'TASK':              'classification',
        'CONNECTIVITY_TYPE': connectivity,
        'ATLAS':             HEADLINE_ATLAS,
    }
    return [run_one(
        f'validate_{dataset}_permute',
        {**common, 'LABEL_PERMUTE': '1'},
    )]


def cmd_classify(dataset: str, atlas: str,
                 connectivity: str = 'voxel',
                 keep_cache: bool = True,
                 results_subdir: str = '',
                 ) -> list[tuple[str, int, float]]:
    """Single classification cell.

    `keep_cache=True` (the default) preserves the local feature cache after
    the run — right for manual single cells that may be repeated.
    Multi-cell batch subcommands (run_standard_atlases / run_sp_atlases /
    run_custom_atlases / run_group_ensemble / compare / all) pass
    `keep_cache=False` so a multi-atlas pass does not accumulate the
    per-atlas feature caches on disk.

    `results_subdir` adds a nesting level under results/ch{N}/ — e.g. the
    SP set sets 'SP_classification/{dataset}' so its 120 cells per dataset
    don't clutter the chapter root.

    Skip-if-exists: if the run dir already contains metrics_subject.json,
    the cell is skipped (returns rc=0), so an interrupted multi-cell run
    resumes where it stopped.
    """
    name = f'{dataset}_classification_{connectivity}_{atlas}'
    # Skip-if-exists check.
    chapter = os.environ.get('CHAPTER', '5')
    run_dir = os.path.join(REPO_ROOT, 'results', f'ch{chapter}',
                           results_subdir, name) if results_subdir else \
              os.path.join(REPO_ROOT, 'results', f'ch{chapter}', name)
    if os.path.isfile(os.path.join(run_dir, 'metrics_subject.json')):
        print(f"[skip] {name} already complete "
              f"(metrics_subject.json exists in {run_dir})", flush=True)
        return [(name, 0, 0.0)]

    print(f"\n{'#' * 70}\n# CLASSIFY — {dataset} {connectivity} {atlas}\n{'#' * 70}\n",
          flush=True)
    env = {
        'DATASET':           dataset,
        'TASK':              'classification',
        'CONNECTIVITY_TYPE': connectivity,
        'ATLAS':             atlas,
        'KEEP_CACHE':        '1' if keep_cache else '0',
    }
    if results_subdir:
        env['RESULTS_SUBDIR'] = results_subdir
    # Auto-drop batch for memory-heavy atlases (T4 has 16 GB VRAM).
    if atlas in BIG_ATLAS_BATCH_OVERRIDES:
        env['BATCH_SIZE'] = BIG_ATLAS_BATCH_OVERRIDES[atlas]
        print(f"  [memory] {atlas} → BATCH_SIZE={env['BATCH_SIZE']}", flush=True)
    return [run_one(name, env)]


def cmd_run_standard_atlases(dataset: str,
                    connectivity: str = 'voxel') -> list[tuple[str, int, float]]:
    """All standard atlases for one dataset, one classification cell each.
    Each cell's feature cache is removed after the cell (KEEP_CACHE=0)."""
    atlases = GSP_ATLASES if dataset == 'gsp' else ABIDE_ATLASES
    print(f"\n{'#' * 70}\n# RUN STANDARD ATLASES — {dataset} {connectivity}  "
          f"({len(atlases)} cells)\n{'#' * 70}\n",
          flush=True)
    results = []
    for atlas in atlases:
        results.extend(cmd_classify(dataset, atlas, connectivity, keep_cache=False))
    return results


def cmd_compare(atlas: str,
                connectivity: str = 'voxel') -> list[tuple[str, int, float]]:
    """Same atlas on both datasets — direct comparison cell."""
    print(f"\n{'#' * 70}\n# COMPARE — GSP vs ABIDE at {connectivity} {atlas}\n{'#' * 70}\n",
          flush=True)
    results = []
    results.extend(cmd_classify('gsp',   atlas, connectivity, keep_cache=False))
    results.extend(cmd_classify('abide', atlas, connectivity, keep_cache=False))
    return results


def cmd_run_sp_atlases(dataset: str,
                 connectivity: str = 'roi_roi') -> list[tuple[str, int, float]]:
    """All stochastic parcellation atlases for one dataset (Ch6).

    Cell count = 4 scales × SP_SAMPLES_PER_K (default 30) = 120. Defaults to
    roi_roi (the MLP), the representation used for the stochastic set in
    the thesis.

    Results land under results/ch{N}/SP_classification/{dataset}/. Each
    cell's feature cache is removed after the cell, and cells with an
    existing metrics_subject.json are skipped. After the per-cell pass:
      - aggregate_sp_metrics.py writes per-scale distribution stats to
        _summary/;
      - aggregate_ensemble.py writes, for each scale, the soft-vote
        ensemble of its samples to
        _ensemble/{dataset}_classification_{conn}_SP_v2_{scale}_ensemble/.
    """
    print(f"\n{'#' * 70}\n# RUN SP ATLASES — {dataset} {connectivity}  "
          f"({len(SP_ATLASES)} cells)\n{'#' * 70}\n",
          flush=True)
    subdir = f'SP_classification/{dataset}'
    results = []
    for atlas in SP_ATLASES:
        results.extend(cmd_classify(dataset, atlas, connectivity,
                                    keep_cache=False, results_subdir=subdir))

    # Per-scale metric distribution aggregation. Runs unconditionally —
    # cheap, just reads JSONs from disk and writes CSV/MD/PNG.
    print(f"\n[run_sp_atlases] aggregating per-scale stats → "
          f"results/ch{os.environ.get('CHAPTER', '6')}/{subdir}/_summary/",
          flush=True)
    agg_cmd = [
        sys.executable, 'src/aggregate_sp_metrics.py',
        '--chapter',      os.environ.get('CHAPTER', '6'),
        '--dataset',      dataset,
        '--connectivity', connectivity,
    ]
    rc = subprocess.run(agg_cmd, cwd=str(REPO_ROOT)).returncode
    results.append((f'sp_metrics_summary_{dataset}_{connectivity}', rc, 0.0))

    # Soft-vote ensemble of the samples at each scale.
    for k in SP_SCALES:
        out_name = f'{subdir}/_ensemble/{dataset}_classification_{connectivity}_SP_v2_{k:03d}_ensemble'
        components = [
            f'{subdir}/{dataset}_classification_{connectivity}_SP_v2_{k:03d}_{n:02d}'
            for n in range(1, SP_SAMPLES_PER_K + 1)
        ]
        ens_cmd = [
            sys.executable, 'src/aggregate_ensemble.py',
            '--chapter',     os.environ.get('CHAPTER', '6'),
            '--output-name', out_name,
            '--components',  *components,
        ]
        rc = subprocess.run(ens_cmd, cwd=str(REPO_ROOT)).returncode
        results.append((out_name, rc, 0.0))
    return results


# Group-mean parcellations (K = 200) of the train-only STAI-T tertiles
# (cut-offs 32/40), built with anxiety-fmri-parcellations
# (run_group_parcellation_split.py) and stored in src/templates/atlases/.
GROUP_TERTILE_ATLASES = ['group_gm_low', 'group_gm_mid', 'group_gm_high']


def cmd_run_group_ensemble(connectivity: str = 'roi_roi',
                           upload: bool = False) -> list[tuple[str, int, float]]:
    """Ch6 group parcellation ensemble.

    Trains 3 separate models (one per train-derived tertile parcellation),
    then averages per-subject probabilities at test. Every subject's
    features are computed under all 3 parcellations, so no subject's label
    decides which parcellation is applied.

    Pipeline:
      1. compute_features.py for the 3 parcellations (existing features are
         skipped; with upload=True they are also written to the S3 bucket)
      2. classify × 3 parcellations → 3 component result dirs
      3. aggregate_ensemble.py      → 1 ensemble result dir

    GSP only (the tertile parcellations are derived from GSP STAI-T scores).
    """
    print(f"\n{'#' * 70}\n# GROUP ENSEMBLE — gsp {connectivity}  "
          f"({len(GROUP_TERTILE_ATLASES)} component models + 1 ensemble)\n"
          f"{'#' * 70}\n", flush=True)

    # Step 1: compute features for the 3 parcellations. Always does BOTH
    # connectivity types — each BOLD is read once per subject, so emitting
    # voxel + roi_roi in the same pass is cheaper than two separate passes.
    # Existing features are skipped.
    print(f"[group_ensemble] step 1/3: feature compute "
          f"(voxel + roi_roi × {len(GROUP_TERTILE_ATLASES)} parcellations)", flush=True)
    feat_cmd = [
        sys.executable, 'src/compute_features.py',
        '--dataset', 'gsp',
        '--atlases', *GROUP_TERTILE_ATLASES,
        '--features', 'voxel', 'roi_roi',
        '--workers', '8',
    ]
    if upload:
        feat_cmd.append('--upload')
    t0 = time.time()
    rc = subprocess.run(feat_cmd, cwd=str(REPO_ROOT)).returncode
    if rc != 0:
        print(f"[group_ensemble] feature compute FAILED rc={rc}; aborting",
              flush=True)
        return [('group_ensemble_features', rc, time.time() - t0)]
    print(f"[group_ensemble] feature compute done in "
          f"{(time.time()-t0)/60:.1f} min", flush=True)

    # Step 2: train one model per mask.
    print(f"[group_ensemble] step 2/3: train {len(GROUP_TERTILE_ATLASES)} "
          f"component models", flush=True)
    results = []
    for atlas in GROUP_TERTILE_ATLASES:
        results.extend(cmd_classify('gsp', atlas, connectivity, keep_cache=False))

    # Step 3: ensemble.
    print(f"[group_ensemble] step 3/3: aggregate predictions", flush=True)
    out_name = f'gsp_classification_{connectivity}_group_gm_ensemble'
    component_names = [
        f'gsp_classification_{connectivity}_{a}' for a in GROUP_TERTILE_ATLASES
    ]
    agg_cmd = [
        sys.executable, 'src/aggregate_ensemble.py',
        '--chapter', os.environ.get('CHAPTER', '6'),
        '--output-name', out_name,
        '--components', *component_names,
    ]
    t0 = time.time()
    rc = subprocess.run(agg_cmd, cwd=str(REPO_ROOT)).returncode
    results.append((out_name, rc, time.time() - t0))
    return results


def cmd_run_custom_atlases(connectivity: str = 'roi_roi') -> list[tuple[str, int, float]]:
    """Individual GSP parcellations (Ch6).

    GSP only. Features are computed by anxiety-fmri-parcellations, so this
    runs `classify` on the individual parcellation features. Defaults to
    roi_roi; pass --connectivity voxel for the 3D CNN on the fingerprints.
    """
    print(f"\n{'#' * 70}\n# RUN CUSTOM ATLASES — gsp {connectivity}  "
          f"({len(CUSTOM_GSP_PARCELLATIONS)} cells)\n{'#' * 70}\n", flush=True)
    results = []
    for atlas in CUSTOM_GSP_PARCELLATIONS:
        results.extend(cmd_classify('gsp', atlas, connectivity, keep_cache=False))
    return results


def cmd_all(connectivity: str = 'voxel') -> list[tuple[str, int, float]]:
    """validate (both) → run_standard_atlases (both)."""
    results = []
    results.extend(cmd_validate('gsp',   connectivity))
    results.extend(cmd_validate('abide', connectivity))
    results.extend(cmd_run_standard_atlases('gsp',   connectivity))
    results.extend(cmd_run_standard_atlases('abide', connectivity))
    return results


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

DATASETS     = ['gsp', 'abide']
CONNECT_OPTS = ['voxel', 'roi_roi']

# Subcommands whose results belong to Chapter 6; every other subcommand
# writes to results/ch5/. An explicit CHAPTER env var overrides both.
CH6_COMMANDS = {'run_sp_atlases', 'run_custom_atlases', 'run_group_ensemble'}


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = ap.add_subparsers(dest='cmd', required=True)

    av = sub.add_parser('validate', help='negative control at cc200')
    av.add_argument('--dataset',      required=True, choices=DATASETS)
    av.add_argument('--connectivity', default='voxel', choices=CONNECT_OPTS)

    ac = sub.add_parser('classify', help='one classification cell')
    ac.add_argument('--dataset',      required=True, choices=DATASETS)
    ac.add_argument('--atlas',        required=True)
    ac.add_argument('--connectivity', default='voxel', choices=CONNECT_OPTS)

    asw = sub.add_parser('run_standard_atlases',
                         help='run all 9 standard atlases for one dataset')
    asw.add_argument('--dataset',      required=True, choices=DATASETS)
    asw.add_argument('--connectivity', default='voxel', choices=CONNECT_OPTS)

    spsw = sub.add_parser('run_sp_atlases',
                          help='Ch6 stochastic parcellation set: 4 scales x '
                               'SP_SAMPLES_PER_K samples (default 30 = 120 cells), '
                               'per-scale summary and soft-vote ensembles')
    spsw.add_argument('--dataset',      required=True, choices=DATASETS)
    spsw.add_argument('--connectivity', default='roi_roi', choices=CONNECT_OPTS)

    csw = sub.add_parser('run_custom_atlases',
                         help='Ch6 individual GSP parcellations (tcorr, K = 200)')
    csw.add_argument('--connectivity', default='roi_roi', choices=CONNECT_OPTS)

    ge = sub.add_parser('run_group_ensemble',
                        help='Ch6 group-mean tertile parcellation ensemble '
                             '(features for 3 parcellations + 3 component models + ensemble)')
    ge.add_argument('--connectivity', default='roi_roi', choices=CONNECT_OPTS)
    ge.add_argument('--upload', action='store_true',
                    help='also upload the computed features to s3://<FMRI_S3_BUCKET>/ '
                         "and delete each subject's local BOLD once all of "
                         'its features are uploaded')

    acmp = sub.add_parser('compare', help='same atlas on both datasets')
    acmp.add_argument('--atlas',        required=True)
    acmp.add_argument('--connectivity', default='voxel', choices=CONNECT_OPTS)

    apall = sub.add_parser('all', help='validate + run_standard_atlases on both datasets')
    apall.add_argument('--connectivity', default='voxel', choices=CONNECT_OPTS)

    args = ap.parse_args()
    os.environ.setdefault('CHAPTER', '6' if args.cmd in CH6_COMMANDS else '5')

    t_total = time.time()
    if args.cmd == 'validate':
        results = cmd_validate(args.dataset, args.connectivity)
    elif args.cmd == 'classify':
        results = cmd_classify(args.dataset, args.atlas, args.connectivity)
    elif args.cmd == 'run_standard_atlases':
        results = cmd_run_standard_atlases(args.dataset, args.connectivity)
    elif args.cmd == 'run_sp_atlases':
        results = cmd_run_sp_atlases(args.dataset, args.connectivity)
    elif args.cmd == 'run_custom_atlases':
        results = cmd_run_custom_atlases(args.connectivity)
    elif args.cmd == 'run_group_ensemble':
        results = cmd_run_group_ensemble(args.connectivity, upload=args.upload)
    elif args.cmd == 'compare':
        results = cmd_compare(args.atlas, args.connectivity)
    elif args.cmd == 'all':
        results = cmd_all(args.connectivity)

    total_min = (time.time() - t_total) / 60
    print('\n' + '=' * 70, flush=True)
    print(f'[run] DONE. {len(results)} cells in {total_min:.1f} min total')
    print('=' * 70)
    for name, rc, dt in results:
        status = 'OK' if rc == 0 else f'FAIL rc={rc}'
        print(f'  [{status}] {name}  ({dt/60:.1f} min)')

    failed = [r for r in results if r[1] != 0]
    sys.exit(0 if not failed else 1)


if __name__ == '__main__':
    main()
